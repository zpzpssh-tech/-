BRAND = re.compile(r"(물리치료사가\s*(직접\s*)?판매하는|물리치료사가\s*추천하는|올투게더나우|보호대연구소|"
                   r"보호대 연구소|휴책|유큐어|큐디아|국내\s*생산|국내생산)")


def clean(name: str) -> str:
    """브랜드·수식어를 지운 비교용 이름."""
    return re.sub(r"\s+", " ", BRAND.sub(" ", str(name or ""))).strip()


def classify(name: str) -> str:
    """상품명을 통합 품목 이름으로 바꿉니다. 못 찾으면 '미분류'."""
    t = clean(name)
    for label, needs, skips in RULES:
        if any(k in t for k in skips):
            continue
        for group in needs:
            if all(k in t for k in group):
                return label
    return "미분류"


# ── 옵션에서 수량·사이즈 뽑기 ──
PAIR = [("양쪽", ["양쪽", "양팔", "1쌍", "2개", "2p", "2P", "2입", "양측"]),
        ("한쪽", ["한쪽", "한팔", "1개", "1p", "1P", "한측", "오른쪽", "왼쪽", "우측", "좌측"]),
        ("세트", ["1세트", "1set", "1SET", "세트"])]
SIZE = re.compile(r"(?<![A-Za-z0-9])(3XL|2XL|XXL|XL|XS|[SML])(?![A-Za-z0-9])")


def variant(opt: str) -> str:
    """옵션에서 '양쪽 · L' 처럼 발주에 필요한 구분만 뽑습니다."""
    t = str(opt or "")
    qty = ""
    for label, keys in PAIR:
        if any(k in t for k in keys):
            qty = label
            break
    # 치수(30 x 20 cm)는 사이즈가 아니므로 뺍니다
    t2 = re.sub(r"\d+(\.\d+)?\s*[xX×]\s*\d+(\.\d+)?\s*(cm|mm)?", " ", t)
    t2 = re.sub(r"\d{3}\s*~\s*\d{3}\s*mm", " ", t2)
    m = SIZE.search(t2)
    size = m.group(1) if m else ""
    return " · ".join([x for x in (qty, size) if x]) or "구분 없음"
