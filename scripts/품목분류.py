def clean(name: str) -> str:
    """브랜드·수식어를 지운 비교용 이름."""
    return re.sub(r"\s+", " ", BRAND.sub(" ", str(name or ""))).strip()


def classify(name: str) -> str:
    """상품명을 통합 품목 이름으로 바꿉니다. 못 찾으면 '미분류'."""
    t = clean(name)
    for label, needs, skips in RULES:
        if any(k in t for k in skips):
            continue
        for group in needs:
            if all(k in t for k in group):
                return label
    return "미분류"


# ── 옵션에서 수량·사이즈 뽑기 ──
PAIR = [("양쪽", ["양쪽", "양팔", "1쌍", "2개", "2p", "2P", "2입", "양측"]),
        ("한쪽", ["한쪽", "한팔", "1개", "1p", "1P", "한측", "오른쪽", "왼쪽", "우측", "좌측"]),
        ("세트", ["1세트", "1set", "1SET", "세트"])]
SIZE = re.compile(r"(?<![A-Za-z0-9])(3XL|2XL|XXL|XL|XS|[SML])(?![A-Za-z0-9])")


# 좌우가 없는 물건은 '한쪽/양쪽'으로 나누지 않습니다.
# 허리·목처럼 몸 가운데 차는 보호대는 쿠팡 옵션의 '1개'가 한쪽이라는 뜻이 아니라 그냥 수량입니다.
NO_SIDE = {"파스·쿨링젤", "찜질팩", "악력기", "마사지볼", "테이핑 테이프",
           "전완 운동도구", "기타 소품", "아치업 깔창", "발아치패드", "경추 목보호대"}
NO_SIDE_WORDS = ("허리", "복대", "척추", "경추", "자세교정")


def no_side(item: str) -> bool:
    t = str(item or "")
    return t in NO_SIDE or any(w in t for w in NO_SIDE_WORDS)


def variant(opt: str, item: str = "", name: str = "") -> str:
    """옵션에서 '양쪽 · L' 처럼 발주에 필요한 구분만 뽑습니다.

    옵션에 수량이 없으면(색상만 고르는 상품) 상품명에서 찾습니다.
    예) '쫀쫀 손목 보호대 아대 2p' + '색상: 블랙' → 양쪽
    """
    t = str(opt or "")
    pairs = [] if no_side(item) else PAIR
    qty = ""
    for source in (t, str(name or "")):
        for label, keys in pairs:
            if any(k in source for k in keys):
                qty = label
                break
        if qty:
            break
    # 치수(30 x 20 cm)는 사이즈가 아니므로 뺍니다
    t2 = re.sub(r"\d+(\.\d+)?\s*[xX×]\s*\d+(\.\d+)?\s*(cm|mm)?", " ", t)
    t2 = re.sub(r"\d{3}\s*~\s*\d{3}\s*mm", " ", t2)
    m = SIZE.search(t2)
    size = m.group(1) if m else ""
    return " · ".join([x for x in (qty, size) if x]) or "구분 없음"


# ── 네이버 '추가구성' 옵션 가려내기 ──
# 옵션이 '그룹이름: 값' 꼴일 때, 그룹이름이 수량·색상 같은 일반 구분이면 그 상품의 옵션이고,
# '아치업 깔창', '바른요 허리보호대'처럼 다른 상품 이름이면 같이 산 추가구성입니다.
# 추가구성은 부모 상품이 아니라 그 상품의 판매량으로 세야 발주 수량이 맞습니다.
GENERIC = {"수량", "색상", "사이즈", "컬러", "방향", "좌우", "좌우선택", "손방향",
           "종류", "옵션", "타입", "구성", "선택", "size", "color", "type"}


def _is_generic(group: str) -> bool:
    t = re.sub(r"[^0-9A-Za-z가-힣]", "", str(group or "")).lower()
    return t in GENERIC


def addon(opt: str):
    """추가구성이면 (상품이름, 고른 값), 아니면 None."""
    for part in str(opt or "").split("/"):
        if ":" not in part:
            continue
        group, value = part.split(":", 1)
        if _is_generic(group):
            continue
        return group.strip(), value.strip()
    return None
